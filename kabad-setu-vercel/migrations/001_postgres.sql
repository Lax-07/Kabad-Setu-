CREATE TABLE IF NOT EXISTS collectors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, phone TEXT NOT NULL UNIQUE, id_type TEXT NOT NULL,
 id_last4 TEXT NOT NULL, verification_status TEXT DEFAULT 'pending',
 address TEXT NOT NULL, lat DOUBLE PRECISION, lng DOUBLE PRECISION, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, role TEXT NOT NULL, user_id BIGINT NOT NULL, expires DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS recyclers (
 id BIGINT PRIMARY KEY, name TEXT, address TEXT, lat DOUBLE PRECISION, lng DOUBLE PRECISION, materials TEXT, initials TEXT,
 operating_hours TEXT NOT NULL DEFAULT '09:00–18:00, Monday–Saturday'
);
ALTER TABLE recyclers ADD COLUMN IF NOT EXISTS operating_hours TEXT NOT NULL DEFAULT '09:00–18:00, Monday–Saturday';
CREATE TABLE IF NOT EXISTS lots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 collector_id BIGINT NOT NULL REFERENCES collectors(id), image BYTEA NOT NULL,
 mime TEXT NOT NULL, items TEXT NOT NULL, source TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pickups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id BIGINT NOT NULL UNIQUE REFERENCES lots(id), collector_id BIGINT NOT NULL REFERENCES collectors(id),
 recycler_id BIGINT NOT NULL REFERENCES recyclers(id), pickup_date TEXT NOT NULL, slot TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'scheduled', total DOUBLE PRECISION NOT NULL, created_at TEXT NOT NULL,
 pickup_address TEXT NOT NULL, pickup_lat DOUBLE PRECISION, pickup_lng DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recycler_id BIGINT NOT NULL REFERENCES recyclers(id), pickup_id BIGINT NOT NULL REFERENCES pickups(id),
 message TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS otp_requests (
 phone TEXT PRIMARY KEY, last_sent DOUBLE PRECISION NOT NULL, window_started DOUBLE PRECISION NOT NULL,
 send_count INTEGER NOT NULL, attempts INTEGER NOT NULL, code_hash TEXT
);
CREATE TABLE IF NOT EXISTS phone_verifications (
 token_hash TEXT PRIMARY KEY, phone TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL
);
CREATE SCHEMA IF NOT EXISTS evidence;
CREATE TABLE IF NOT EXISTS evidence.proofs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pickup_id BIGINT UNIQUE NOT NULL REFERENCES public.pickups(id), recycler_id BIGINT NOT NULL REFERENCES public.recyclers(id),
 image BYTEA NOT NULL, mime TEXT NOT NULL, sha256 TEXT NOT NULL, recorded_at TEXT NOT NULL,
 captured_at TEXT NOT NULL, lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL, accuracy DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS pickups_collector_idx ON pickups(collector_id, id DESC);
CREATE INDEX IF NOT EXISTS pickups_recycler_idx ON pickups(recycler_id, id DESC);
CREATE INDEX IF NOT EXISTS notifications_recycler_idx ON notifications(recycler_id, id DESC);
